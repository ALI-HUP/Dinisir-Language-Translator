import { NextResponse } from "next/server";
import { GoogleGenAI } from "@google/genai";

const apiKey = process.env.GEMINI_API_KEY;

export async function POST(req: Request) {
  try {
    if (!apiKey) {
      return NextResponse.json(
        { error: "کلید GEMINI_API_KEY تنظیم نشده است." },
        { status: 500 },
      );
    }

    const { text } = await req.json();

    if (!text) {
      return NextResponse.json(
        { error: "متنی ارسال نشده است." },
        { status: 400 },
      );
    }

    const ai = new GoogleGenAI({ apiKey });

    const systemPrompt = `
      [نقش و هدف]
      شما یک موتور تبدیل متنی بسیار دقیق و بدون خطای انسانی هستید. وظیفه شما تبدیل متن ورودی به "زبان دینیسیری" (لحن طنز دایناسور بدون فک) طبق الگوریتم، قوانین ساختاری و املایی اکید زیر است.

      [الگوریتم و قوانین تبدیل]
      ۱. **قانون اصلی (جایگزینی مصوت‌ها):**
        - تمامی مصوت‌های کوتاه ( َ  ِ  ُ ) و مصوت‌های بلند (آ، ا) باید به حرف "ی" تبدیل شوند. (مثال: "زبان" ⬅️ "زیبین" | "سلام" ⬅️ "سیلیم").
        - از هیچ اعراب یا حرکتی در خروجی استفاده نکنید.
        - **اکیداً رعایت شود:** صامت‌های ساکن (حروفی که هیچ مصوتی ندارند) به هیچ وجه نباید حرف "ی" بگیرند. (مثال: در "کَردی"، حرف "ر" ساکن است ⬅️ "کیردی" | در "فکر"، حرف "ک" ساکن است ⬅️ "فیکر").

      ۲. **قانون حرف "و" با صدای مصوت (ُ):**
        - حرف "و" در کلماتی که صدای (ُ) می‌دهند (مثل: خود، خوش، خودت)، فقط و فقط به یک حرف "ی" تبدیل می‌شود. هرگز "یی" تولید نکنید! (مثال: "خودتی" ⬅️ "خیدیتی" [نه خییدیتی] | "خوشحال" ⬅️ "خیشحیل").

      ۳. **کلمات تک‌هجایی و حروف اضافه کوتاه (بسیار مهم):**
        - کلماتی که فقط شامل یک مصوت بلند هستند (مانند حرف اضافه "با")، نباید تبدیل به "یی" یا حروف تکراری شوند. فقط به یک "ی" ختم می‌شوند. (مثال: "با" ⬅️ "بی" [نه بیی]).

      ۴. **قالب‌های دقیق برای ترکیبات "یا" و "ایم":**
        - کلمات دو هجایی ختم‌شده به «یا» (مثل بیا) ⬅️ تبدیل به «بیی» می‌شوند. (مثال: "بیا" ⬅️ "بیی").
        - کلمات ختم‌شده به «ه‌ایم/ایم» (مثل عقده‌ایم) ⬅️ تبدیل به «یم» می‌شوند. (مثال: "عقده‌ایم" ⬅️ "عیقدیم").

      ۵. **جلوگیری از ساختن "ی" تکراری (قانون املایی اکید):**
        - در کلماتی که دارای ضمه در هجای اول هستند (مانند قربون، قربونت)، هجای اول فقط یک "ی" می‌گیرد و هرگز نباید "یی" نوشته شود. (مثال: "قربونت" ⬅️ "قیربینیت" [نه قییربینیت]).
        - به طور کلی، وجود بیش از یک "ی" متوالی (مثل "یی") در داخل کلمات ممنوع است؛ مگر در انتهای کلمات خاص مانند "بیا" ⬅️ "بیی".

      ۶. **الف ابتدای کلمه:**
        - کلماتی که با "آ" یا "ا" شروع می‌شوند ⬅️ تبدیل به "ایـ" می‌شوند. (مثال: "آکله" ⬅️ "ایکیلی" | "امروز" ⬅️ "ایمریز" | "این" ⬅️ "این").

      ۷. **حذف واو معدوله (ناخوانا):**
        - در کلماتی که "واو" نوشته می‌شود اما "آ" خوانده می‌شود (مثل: می‌خوام، خواستن، خواندن، استخوان)، حرف "واو" کلاً حذف شده و مصوت آن به "ی" تبدیل می‌شود. (مثال: "می‌خوام" ⬅️ "میخیم" | "خواستن" ⬅️ "خیستین").

      ۸. **حفظ املای صامت‌ها:**
        - تمام حروف صامت اصلی (ع، ث، ص، ض، ط، ظ، ح، غ و...) باید دقیقاً حفظ شوند و نباید تغییر کنند. (مثال: "کثافت" ⬅️ "کیثیفیت" | "عقده" ⬅️ "عیقدی").

      ۹. **شناسه افعال اول شخص (م):**
        - افعال انتهایی اول شخص (ختم شده به "م") نباید به "می" ختم شوند. حرف قبل از "م" تبدیل به "ی" می‌شود. (مثال: "برقصم" ⬅️ "بیریقصیم").

      [محدودیت‌های خروجی - اکیداً رعایت شود]
      - فقط و فقط متن تبدیل‌شده نهایی را برگردانید.
      - علائم نگارشی (مثل ؟ ، ! .) را حفظ کنید.
      - هیچ کلمه اضافی، تحلیل، توضیح، پرانتز، ایموجی، غرش (مثل ROAR) یا کاراکتر انگلیسی نباید در خروجی باشد.

      [مثال‌های الگو (Few-shot)]
      ورودی: دلم برات تنگ شده، کی میای همدیگه رو ببینیم؟ بیا با هم بریم ددر دودور قربونت برم ⬅️ خروجی: دیلیم بیریت تینگ شیدی، کی مییی هیمدیگی ری بیبینیم؟ بیی بی هیم بیریم دیدیر دیدیر قیربینیت بیریم
      ورودی: این زبان دیسینیر هست مسخره هم خودتی ⬅️ خروجی: این زیبین دیسینیر هیست میسخیری هیم خیدیتی
      ورودی: امروز می‌خوام آب بخورم ⬅️ خروجی: ایمریز میخیم ایب بیخیریم
      ورودی: من عقده‌ایم کثافت ⬅️ خروجی: مین عیقدیم کیثیفیت
      ورودی: آکله بگیری الهی ⬅️ خروجی: ایکیلی بیگیری ایلیهی
      ورودی: بیناموس دلقک فکر کردی کی هستی ⬅️ خروجی: بینیمیس دیلیقیک فیکر کیردی کی هیستی؟
      ورودی: سلام چطوری خوبی؟ ⬅️ خروجی: سیلیم چیطیری خیبی؟
      ورودی: بیا برات برقصم ⬅️ خروجی: بیی بیریت بیریقصیم
      ورودی: امروز رفتم مغازه ⬅️ خروجی: ایمریز ریفتیم میغیزی

      متن ورودی جهت تبدیل:
      "${text}"
    `;

    const response = await ai.models.generateContent({
      model: "gemini-3.1-flash-lite",
      contents: systemPrompt,
    });

    const result = response.text?.trim() || "سیلیم!";

    return NextResponse.json({ result });
  } catch (error: any) {
    console.error("Gemini API Error:", error);
    if (error?.status === 429) {
      return NextResponse.json(
        {
          error: "تعداد درخواست‌هات زیاده! پررو شدی...",
        },
        { status: 429 },
      );
    }
    return NextResponse.json(
      { error: "هوش مصنوعی‌مون نمی‌هوشه! شیرمیندی..." },
      { status: 500 },
    );
  }
}
