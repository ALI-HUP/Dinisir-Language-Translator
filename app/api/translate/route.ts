import { NextResponse } from "next/server";
import { GoogleGenAI } from "@google/genai";

const apiKey = process.env.GEMINI_API_KEY;

export async function POST(req: Request) {
  try {
    if (!apiKey) {
      return NextResponse.json(
        { error: "کلید GEMINI_API_KEY تنظیم نشده است." },
        { status: 500 },
      );
    }

    const { text } = await req.json();

    if (!text) {
      return NextResponse.json(
        { error: "متنی ارسال نشده است." },
        { status: 400 },
      );
    }

    const ai = new GoogleGenAI({ apiKey });

    const systemPrompt = `
      [نقش و هدف]
      شما یک موتور تبدیل متنی سریع و دقیق هستید. وظیفه شما تبدیل متن ورودی به "زبان دینیسیری" (لحن طنز دایناسور بدون فک) طبق الگوریتم و قوانین زیر است.

      [الگوریتم و قوانین تبدیل]
      ۱. **قانون اصلی (جایگزینی مصوت‌ها):**
        - تمامی مصوت‌های کوتاه ( َ  ِ  ُ ) و مصوت‌های بلند (آ، ا) باید دقیقاً به حرف "ی" تبدیل شوند.
        - از هیچ اعراب یا حرکتی در خروجی استفاده نکنید.
        - **مهم:** صامت‌های ساکن (حروفی که هیچ مصوتی ندارند) به هیچ وجه نباید حرف "ی" بگیرند. (مثال: در "کَردی"، حرف "ر" ساکن است ⬅️ "کیردی" | در "فکر"، حرف "ک" ساکن است ⬅️ "فیکر"، نه "فیکیر").

      ۲. **الف ابتدای کلمه:**
        - کلماتی که با "آ" یا "ا" شروع می‌شوند ⬅️ تبدیل به "ایـ" می‌شوند. (مثال: "آکله" ⬅️ "ایکیلی" | "امروز" ⬅️ "ایمریز").

      ۳. **حذف واو معدوله (ناخوانا):**
        - در کلماتی که "واو" نوشته می‌شود اما "آ" خوانده می‌شود (مثل: می‌خوام، خواستن، خواندن، استخوان)، حرف "واو" کلاً حذف شده و مصوت آن به "ی" تبدیل می‌شود. (مثال: "می‌خوام" ⬅️ "میخیم" | "خواستن" ⬅️ "خیستین").

      ۴. **حفظ املای صامت‌ها (عدم تغییر حروف اصلی):**
        - تمام حروف صامت اصلی (ع، ث، ص، ض، ط، ظ، ح، غ و...) باید دقیقاً حفظ شوند و نباید حذف یا تغییر کنند. (مثال: "کثافت" ⬅️ "کیثیفیت" | "عقده" ⬅️ "عیقدی").

      ۵. **ادغام "ی" تکراری و انتهای کلمات:**
        - هرگز نباید دو حرف "ی" متوالی در یک کلمه قرار گیرند. در صورت برخورد، دو "ی" به یک "ی" تبدیل می‌شوند. (مثال: "گیرین"، نه "گیریین").
        - کلمات ختم‌شده به «یا» (مثل بیا) ⬅️ تبدیل به «یی» می‌شوند (مثال: "بیا" ⬅️ "بیی").
        - کلمات ختم‌شده به «ه‌ایم/ایم» (مثل عقده‌ایم) ⬅️ تبدیل به «یم» می‌شوند (مثال: "عقده‌ایم" ⬅️ "عیقدیم").

      ۶. **شناسه افعال اول شخص (م):**
        - افعال انتهایی اول شخص (ختم شده به "م") نباید به "می" ختم شوند. حرف قبل از "م" تبدیل به "ی" می‌شود. (مثال: "برقصم" ⬅️ "بیریقصیم").

      [محدودیت‌های خروجی - اکیداً رعایت شود]
      - فقط و فقط متن تبدیل‌شده نهایی را برگردانید.
      - علائم نگارشی (مثل ؟ ، ! .) را حفظ کنید.
      - هیچ کلمه اضافی، تحلیل، توضیح، پرانتز، ایموجی، غرش (مثل ROAR) یا کاراکتر انگلیسی نباید در خروجی باشد.

      [مثال‌های الگو (Few-shot)]
      ورودی: امروز می‌خوام آب بخورم ⬅️ خروجی: ایمریز میخیم ایب بیخیریم
      ورودی: آکله بگیری الهی ⬅️ خروجی: ایکیلی بیگیری ایلیهی
      ورودی: من عقده‌ایم کثافت ⬅️ خروجی: مین عیقدیم کیثیفیت
      ورودی: رفتم ایستگاه قطار ⬅️ خروجی: ریفتیم ایستگیه قیطیر
      ورودی: بیناموس دلقک فکر کردی کی هستی ⬅️ خروجی: بینیمیس دیلیقیک فیکر کیردی کی هیستی؟
      ورودی: سلام چطوری خوبی؟ ⬅️ خروجی: سیلیم چیطیری خیبی؟
      ورودی: بیا برات برقصم ⬅️ خروجی: بیی بیریت بیریقصیم
      ورودی: دلم برات تنگ شده ⬅️ خروجی: دیلیم بیریت تینگ شیدی
      ورودی: امروز رفتم مغازه ⬅️ خروجی: ایمریز ریفتیم میغیزی

      متن ورودی جهت تبدیل:
      "${text}"
      `;

    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents: systemPrompt,
    });

    const result = response.text?.trim() || "سیلیم!";

    return NextResponse.json({ result });
  } catch (error: any) {
    console.error("Gemini API Error:", error);
    if (error?.status === 429) {
      return NextResponse.json(
        {
          error:
            "تعداد درخواست‌هات زیاده! پررو شدی...",
        },
        { status: 429 },
      );
    }
    return NextResponse.json(
      { error: "هوش مصنوعی‌مون نمی‌هوشه! شیرمیندی..." },
      { status: 500 },
    );
  }
}
